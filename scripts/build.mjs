#!/usr/bin/env node
// Builds deployable Deluge from extension/ into dist/.
//
// Deluge has no user-defined functions or imports, so shared code is written as snippets
// in extension/lib/ and pasted where a source says `// @include lib/<name>.dg`. Snippets
// communicate through documented variable names (see each lib file's header).
//
//   node scripts/build.mjs            → builds every entry in extension/manifest.json
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const EXT = path.join(ROOT, 'extension');
const DIST = path.join(ROOT, 'dist');

const INCLUDE = /^[ \t]*\/\/\s*@include\s+(\S+)\s*$/;

export function expand(file, stack = []) {
  const abs = path.resolve(EXT, file);
  if (stack.includes(abs)) throw new Error(`Include cycle: ${[...stack, abs].map((p) => path.relative(EXT, p)).join(' → ')}`);
  if (!fs.existsSync(abs)) throw new Error(`Missing include ${file} (from ${stack.length ? path.relative(EXT, stack.at(-1)) : 'entry'})`);
  return fs.readFileSync(abs, 'utf8').split('\n').map((line) => {
    const m = line.match(INCLUDE);
    return m ? expand(m[1], [...stack, abs]).replace(/\n$/, '') : line;
  }).join('\n');
}

// A rough proxy for Deluge's 5,000-statement limit: statements end in `;`. Loops multiply
// the real count at run time, so this only catches scripts that are large to begin with.
export const statementCount = (src) => src.split('\n').filter((l) => /;\s*(\/\/.*)?$/.test(l) && !/^\s*\/\//.test(l)).length;

// Handlers are size-limited by the platform (a ~49 KB script was refused, ~33 KB accepted),
// so deployed output drops comment-only lines, blank lines and indentation. Deluge does not
// care about whitespace, and deploy errors are reported against dist/ lines anyway.
export const compact = (src) => src.split('\n')
  .map((l) => l.replace(/^[ \t]+/, ''))
  .filter((l) => l !== '' && !l.startsWith('//'))
  .join('\n');

// The manifest is the same for every org; the ids that differ per org (bot, schedulers,
// widget) live in extension/org.json, written by scripts/install.mjs and not committed, so a
// shared repo never carries one org's ids into another's deploy.
export function loadManifest() {
  const manifest = JSON.parse(fs.readFileSync(path.join(EXT, 'manifest.json'), 'utf8'));
  const orgFile = path.join(EXT, 'org.json');
  if (!fs.existsSync(orgFile)) return manifest;
  const org = JSON.parse(fs.readFileSync(orgFile, 'utf8'));
  return {
    ...manifest,
    deployed: true,
    bot: { ...manifest.bot, ...org.bot },
    schedulers: org.schedulers ?? [],
    widget: { ...manifest.widget, ...org.widget },
  };
}

export function buildAll(only) {
  const manifest = loadManifest();
  fs.mkdirSync(DIST, { recursive: true });
  const out = [];
  for (const entry of manifest.entries.filter((e) => !only || only.includes(e.id))) {
    const body = compact(expand(entry.source));
    const header = `// GENERATED by scripts/build.mjs from extension/${entry.source} — edit the source, not this file.\n`;
    const target = path.join(DIST, `${entry.id}.dg`);
    fs.writeFileSync(target, header + body + '\n');
    out.push({ ...entry, dist: target, statements: statementCount(body), bytes: Buffer.byteLength(body) });
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const only = process.argv.slice(2);
  for (const b of buildAll(only.length ? only : undefined)) {
    console.log(`${b.id.padEnd(22)} ${String(b.statements).padStart(5)} statements  ${String(b.bytes).padStart(7)} bytes  → ${path.relative(ROOT, b.dist)}`);
  }
}
